import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import { rateLimit } from 'express-rate-limit';
import { randomUUID } from 'node:crypto';
import { env } from './config/env.js';
import { db } from './config/database.js';
import { authenticate, requirePasswordChanged, requirePermission, requireSociety } from './middleware/auth.js';
import { errorHandler } from './middleware/error.js';
import { societyRouter } from './modules/societies/society.routes.js';
import { authRouter } from './modules/auth/auth.routes.js';
import { memberRouter } from './modules/members/member.routes.js';
import { userRouter } from './modules/users/user.routes.js';
import { uploadRouter } from './modules/uploads/upload.routes.js';
import { dashboardRouter } from './modules/dashboard/dashboard.routes.js';
import { financeRouter } from './modules/finance/finance.routes.js';
export const app = express();
app.disable('x-powered-by');
app.set('trust proxy', env.TRUST_PROXY);
app.use(helmet(), cors({ origin: env.FRONTEND_ORIGIN, credentials: true }), express.json({ limit: '100kb' }), cookieParser());
app.use((_req, res, next) => { res.set('X-Request-Id', randomUUID()); res.set('Cache-Control', 'no-store'); next(); });
app.get('/api/health', async (_req, res) => {
  await db.$queryRaw`SELECT 1`;
  res.json({ status: 'ok', version: '1.1.0', capabilities: { memberPhotoRemoval: true, supersededPhotoCleanup: true, multiSociety: true, memberFinance: true } });
});
// Browser suites share one loopback IP and exercise several users in seconds.
app.use('/api', rateLimit({ windowMs: 60000, limit: env.NODE_ENV === 'test' ? 10000 : 300, standardHeaders: 'draft-8', legacyHeaders: false, message: { error: { message: 'Too many requests. Please wait a minute' } } }));
app.use('/api/auth', authRouter);
app.use('/api', authenticate, requirePasswordChanged);
app.use('/api/societies', societyRouter);
app.use('/api', requireSociety);
app.get('/api/roles', requirePermission('users.manage'), async (_req, res) => res.json(await db.role.findMany({ where: { code: { not: 'SUPER_ADMIN' } }, select: { code: true, name: true }, orderBy: { name: 'asc' } })));
app.use('/api/members', memberRouter);
app.use('/api/users', userRouter);
app.use('/api/dashboard', dashboardRouter);
app.use('/api/finance', financeRouter);
app.use('/api', uploadRouter);
app.use((_req, res) => res.status(404).json({ error: { message: 'Endpoint not found' } }));
app.use(errorHandler);
